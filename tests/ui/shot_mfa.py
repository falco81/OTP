import asyncio, subprocess, os, time, importlib.util
from playwright.async_api import async_playwright
PW=open('/home/claude/run/adminpw').read().strip()
env=dict(os.environ, OTP_CONFIG='/etc/otp/config.json')
spec=importlib.util.spec_from_file_location('otpm','/usr/local/lib/otp/otp.py'); m=importlib.util.module_from_spec(spec); spec.loader.exec_module(m)
subprocess.run(['python3','/usr/local/lib/otp/otp.py','--set','admin_2fa=1'],env=env,capture_output=True)
time.sleep(10)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); ctx=await b.new_context(ignore_https_errors=True, viewport={'width':1920,'height':960})
        pg=await ctx.new_page(); errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('https://127.0.0.1/admin/'); await pg.wait_for_timeout(600)
        await pg.fill('#in-name','admin'); await pg.fill('#in-pass',PW); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(2500)
        await pg.screenshot(path='/home/claude/shots/mfa-enrol.png')
        print('fits', await pg.evaluate("document.documentElement.scrollHeight <= window.innerHeight"), await pg.evaluate("document.documentElement.scrollHeight"))
        await pg.click('.mfa-way >> nth=1'); await pg.wait_for_timeout(500)
        await pg.screenshot(path='/home/claude/shots/mfa-mail.png')
        await pg.click('.mfa-way >> nth=0'); await pg.wait_for_timeout(1200)
        await pg.reload(); await pg.wait_for_timeout(2500)
        print('after reload still mfa', await pg.evaluate("!document.getElementById('mfa-box').hidden"))
        sec = (await pg.locator('.mfa-key').inner_text()).replace(' ','')
        await pg.fill('.mfa-code', m.totp(m.b32_clean(sec))); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(3000)
        print('in app', await pg.evaluate("!!document.getElementById('me-btn')"))
        await pg.goto('https://127.0.0.1/admin/#settings/people'); await pg.wait_for_timeout(3000)
        await pg.locator('#us-table').screenshot(path='/home/claude/shots/mfa-users.png')
        ctx2=await b.new_context(ignore_https_errors=True, viewport={'width':1200,'height':900}); pg2=await ctx2.new_page()
        await pg2.goto('https://127.0.0.1/admin/'); await pg2.fill('#in-name','admin'); await pg2.fill('#in-pass',PW); await pg2.keyboard.press('Enter'); await pg2.wait_for_timeout(2500)
        await pg2.screenshot(path='/home/claude/shots/mfa-check.png')
        print('errors', errs)
        await b.close()
asyncio.run(main())
subprocess.run(['python3','/usr/local/lib/otp/otp.py','--set','admin_2fa=0'],env=env,capture_output=True)
subprocess.run(['python3','/usr/local/lib/otp/otp.py','--reset-2fa','admin'],env=env,capture_output=True)
