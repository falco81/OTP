import asyncio, sys
from playwright.async_api import async_playwright
PW=open('/home/claude/run/adminpw').read().strip()
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); ctx=await b.new_context(ignore_https_errors=True, viewport={'width':1600,'height':1000})
        pg=await ctx.new_page(); errs=[]
        pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('https://127.0.0.1/admin/'); await pg.wait_for_timeout(600)
        await pg.fill('#in-name','admin'); await pg.fill('#in-pass',PW); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(2000)
        await pg.goto('https://127.0.0.1/admin/#settings/fw'); await pg.reload(); await pg.wait_for_timeout(2500)
        await pg.screenshot(path='/home/claude/shots/fw1.png', full_page=False)
        await pg.evaluate("document.querySelector('#fw-body').scrollIntoView()"); await pg.wait_for_timeout(300)
        await pg.screenshot(path='/home/claude/shots/fw2.png')
        await pg.evaluate("document.querySelector('.fw-auto').scrollIntoView()"); await pg.wait_for_timeout(300)
        await pg.screenshot(path='/home/claude/shots/fw3.png')
        await pg.click('text=Add a rule'); await pg.wait_for_timeout(500)
        await pg.screenshot(path='/home/claude/shots/fw4.png')
        await pg.keyboard.press('Escape')
        await pg.goto('https://127.0.0.1/admin/#settings/ha'); await pg.reload(); await pg.wait_for_timeout(2500)
        await pg.evaluate("document.querySelector('#ha-lb').scrollIntoView()"); await pg.wait_for_timeout(300)
        await pg.click('.lb-guide[data-k=haproxy] summary'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='/home/claude/shots/lb1.png')
        await pg.evaluate("document.querySelector('#ha-rep-card').scrollIntoView()"); await pg.wait_for_timeout(300)
        await pg.screenshot(path='/home/claude/shots/rep.png')
        await pg.click('#ha-history'); await pg.wait_for_timeout(1200)
        await pg.screenshot(path='/home/claude/shots/hist.png')
        await pg.keyboard.press('Escape'); await pg.wait_for_timeout(300)
        await pg.evaluate("haErrors()"); await pg.wait_for_timeout(9000)
        await pg.screenshot(path='/home/claude/shots/err.png')
        print('errors', errs)
        await b.close()
asyncio.run(main())
